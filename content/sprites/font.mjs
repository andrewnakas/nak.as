export function glyphRows(c) {
  const g = F[c];
  if (!g) throw new Error(`font: missing glyph for '${c}'`);
  // Pad to 8x8.
  return Array.from({ length: 8 }, (_, y) => (g[y] ?? '').padEnd(8, '.').slice(0, 8));
}
